"""Writes src/pixelfont.ts, Terminal's lettering, from a Terminus bitmap.

    python3 scripts/pixelfont.py ter-u14b_unicode.otb src/pixelfont.ts

The font: Terminus Font (https://terminus-font.sourceforge.net/, SIL Open
Font License 1.1), 8 by 14 pixels, bold. Takes Python with Pillow; only
maintainers run it, and the server uses the generated bitmaps, with no font
installed. Covers the characters src/glyphs.ts does.
"""

import json
import sys

from PIL import Image, ImageDraw, ImageFont

font = ImageFont.truetype(sys.argv[1], 14)
chars = (
    [chr(c) for c in range(32, 127)]
    + [chr(c) for c in range(0xC0, 0x100) if c not in (0xD7, 0xF7)]
    + list("‘’“”–—•…·©")
)
WIDTH, HEIGHT = 8, 14
ascent, _ = font.getmetrics()
bitmaps = {}
for c in chars:
    image = Image.new("1", (WIDTH, HEIGHT), 0)
    ImageDraw.Draw(image).text((0, 0), c, font=font, fill=1)
    # Each row as a number, its leftmost pixel the highest bit
    rows = []
    for y in range(HEIGHT):
        row = 0
        for x in range(WIDTH):
            row = row << 1 | (1 if image.getpixel((x, y)) else 0)
        rows.append(row)
    bitmaps[c] = rows
with open(sys.argv[2], "w") as out:
    out.write(
        "// Generated by scripts/pixelfont.py from Terminus Font (SIL Open Font\n"
        "// License 1.1): each character's 8-by-14 bitmap, a number per row, its\n"
        "// leftmost pixel the highest bit. Don't edit by hand.\n"
        f"export const PIXEL_WIDTH = {WIDTH};\n"
        f"export const PIXEL_HEIGHT = {HEIGHT};\n"
        f"// The baseline, in rows from the top\n"
        f"export const PIXEL_BASELINE = {ascent};\n"
        "export const PIXEL_FONT: Record<string, number[]> = "
        + json.dumps(bitmaps, ensure_ascii=False)
        + ";\n"
    )
print(len(bitmaps), "characters, baseline", ascent)
